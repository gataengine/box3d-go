// TestWidegenUpToDate checks that the generated width-8 kernels match their generic sources.
func TestWidegenUpToDate(t *testing.T) {
	cfg := defaultConfig("../..")
	var out bytes.Buffer
	if err := run(cfg, true, &out); err != nil {
		t.Fatalf("widegen -check: %v\n%s(run `go generate ./...` in libs/box3d-go)", err, out.String())
	}
	files, err := generate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != len(cfg.inputs) {
		t.Fatalf("got %d outputs, want %d", len(files), len(cfg.inputs))
	}
	for _, f := range files {
		text := string(f.src)
		if !strings.HasPrefix(text, "// Code generated by tools/widegen from "+f.input+". DO NOT EDIT.\n") {
			t.Errorf("%s: missing DO-NOT-EDIT header", f.name)
		}
		if !strings.Contains(text, "\n"+buildLine+"\n") {
			t.Errorf("%s: missing build tag %q", f.name, buildLine)
		}
		if strings.Contains(text, "//go:generate") {
			t.Errorf("%s: carries a go:generate directive", f.name)
		}
	}
}

// TestWidegenRenames checks the rename rules on a fixture.
func TestWidegenRenames(t *testing.T) {
	cfg := defaultConfig("testdata/renames")
	cfg.inputs = []string{"kernel_wide.go"}
	cfg.laneFiles = []string{"lanes.go"}
	files, err := generate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 1 || files[0].name != "kernel_wide8_gen.go" {
		t.Fatalf("unexpected outputs %v", files)
	}
	text := string(files[0].src)
	want := []string{
		"// Code generated by tools/widegen from kernel_wide.go. DO NOT EDIT.\n\n" + buildLine + "\n\n// Fixture: a width-generic kernel source.\n",
		"type vecW8 struct {\n\tv floatW8\n}",
		"func (x *vecW8) lenW() floatW8 { return x.v }",
		"func solveW8(x *vecW8, a, b floatW8) floatW8 {",
		"x.v = addW8(a, b)",
		"scale := a // shadows the package-level scale",
		"y := vecW8{v: scale}",
		"return addW8(scale, y.v)",
		"func helperW8(s *state) floatW8 {",
		"s.wideConstraints8 = s.wideConstraints8 + 1",
		"return addW8(scale8, scale8)",
		"// solveW uses a lane function and a struct field.",
	}
	for _, w := range want {
		if !strings.Contains(text, w) {
			t.Errorf("output lacks %q\n--- output ---\n%s", w, text)
		}
	}
	if strings.Contains(text, "go:generate") {
		t.Errorf("output keeps the go:generate directive")
	}
}

// TestWidegenCollision checks that a declared ident+"8" outside the generated files is an error.
func TestWidegenCollision(t *testing.T) {
	cfg := defaultConfig("testdata/collision")
	cfg.inputs = []string{"kernel_wide.go"}
	cfg.laneFiles = []string{"lanes.go"}
	_, err := generate(cfg)
	if err == nil || !strings.Contains(err.Error(), "solveW8") || !strings.Contains(err.Error(), "clash.go") {
		t.Fatalf("want a collision error naming solveW8 in clash.go, got %v", err)
	}
}
